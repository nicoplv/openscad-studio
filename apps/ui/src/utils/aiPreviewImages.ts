import type { ModelMessage, PrepareStepFunction } from 'ai';
import {
  getScaledDimensions,
  imageHasTransparency,
  JPEG_QUALITY,
  loadImageFromDataUrl,
} from './imageData';

const MAX_PREVIEW_IMAGE_EDGE = 800;
const SCREENSHOT_TOOL = 'get_preview_screenshot';

function hasScreenshot(
  output: unknown
): output is { image_data_url: string; __previewKind?: '2d' | '3d' } {
  return (
    typeof output === 'object' &&
    output !== null &&
    'image_data_url' in output &&
    typeof output.image_data_url === 'string' &&
    output.image_data_url.length > 0
  );
}

async function preparePreviewImage(screenshot: {
  image_data_url: string;
  __previewKind?: '2d' | '3d';
}): Promise<string> {
  const image = await loadImageFromDataUrl(screenshot.image_data_url);
  const { width, height } = getScaledDimensions(
    image.naturalWidth,
    image.naturalHeight,
    MAX_PREVIEW_IMAGE_EDGE
  );
  const canvas = document.createElement('canvas');
  canvas.width = width;
  canvas.height = height;
  const ctx = canvas.getContext('2d');
  if (!ctx) {
    throw new Error('Could not create a 2D drawing context.');
  }
  ctx.drawImage(image, 0, 0, width, height);

  const useJpeg = screenshot.__previewKind === '3d' && !imageHasTransparency(ctx, width, height);
  const dataUrl = useJpeg
    ? canvas.toDataURL('image/jpeg', JPEG_QUALITY)
    : canvas.toDataURL('image/png');
  if (!dataUrl.startsWith('data:image/')) {
    throw new Error('Could not encode preview image.');
  }
  return dataUrl;
}

export const prepareOpenAiCompatiblePreviewStep: PrepareStepFunction = async ({
  messages,
  steps,
}) => {
  const latestScreenshot = steps[steps.length - 1]?.toolResults
    .filter(({ toolName, output }) => toolName === SCREENSHOT_TOOL && hasScreenshot(output))
    .pop();
  let image: string | undefined;
  if (hasScreenshot(latestScreenshot?.output)) {
    try {
      image = await preparePreviewImage(latestScreenshot.output);
    } catch {
      // Keep the tool call paired with a short error if the image cannot be encoded.
    }
  }

  const preparedMessages = messages.map((message, index): ModelMessage => {
    if (message.role !== 'tool') return message;
    return {
      ...message,
      content: message.content.map((part): typeof part => {
        if (part.type !== 'tool-result' || part.toolName !== SCREENSHOT_TOOL) return part;
        const { output } = part;
        const hasImage =
          output.type === 'content' ||
          (output.type === 'text' && output.value.includes('data:image/'));
        if (!hasImage) return part;

        const selected =
          index === messages.length - 1 && part.toolCallId === latestScreenshot?.toolCallId;
        return {
          ...part,
          output:
            selected && !image
              ? { type: 'error-text', value: 'Could not prepare the preview image.' }
              : {
                  type: 'text',
                  value: selected
                    ? 'Screenshot captured. Image attached below.'
                    : 'Screenshot captured. Image omitted from this request.',
                },
        };
      }),
    };
  });

  if (image) {
    preparedMessages.push({
      role: 'user',
      content: [
        { type: 'text', text: 'Preview image generated by the Studio screenshot tool.' },
        { type: 'image', image },
      ],
    });
  }

  return { messages: preparedMessages };
};
